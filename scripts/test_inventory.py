#!/usr/bin/env python3
"""Regenerate the test-case inventory in docs/Test_strategy.md from the real suites.

    python3 scripts/test_inventory.py

Collects (does not run) the backend pytest suite, the frontend Vitest suite and
the Playwright suite, and rewrites the block between the inventory markers in
docs/Test_strategy.md. Requirement IDs are taken from the test names
(test_FR_AUTH_01_AC3_... / "FR-AUTH-01 AC3 ..."). Parametrised cases are
collapsed into one line with a count.

Needs uv (backend) and pnpm (frontend) on PATH; no database or browser is used.
"""

import re
import subprocess
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "Test_strategy.md"
START, END = "<!-- inventory:start -->", "<!-- inventory:end -->"
# Underscores are word characters, so look-behinds replace \b.
REQ = re.compile(
    r"(?<![A-Za-z0-9])(FR)[_-]([A-Z0-9]+)[_-](\d{2})(?:[_ -](AC\d+))?"
    r"|(?<![A-Za-z0-9])(NFR)[_-](\d{2})(?![0-9])"
)


Inventory = OrderedDict[str, OrderedDict[str, int]]


def run(command: list[str], cwd: Path) -> str:
    # Fixed tool invocations from this repository; no user input reaches them.
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True, check=False)  # noqa: S603
    return result.stdout


def requirement_ids(name: str) -> str:
    ids: list[str] = []
    for m in REQ.finditer(name):
        if m.group(5):
            ids.append(f"NFR-{m.group(6)}")
        else:
            ident = f"{m.group(1)}-{m.group(2)}-{m.group(3)}"
            ids.append(f"{ident} {m.group(4)}" if m.group(4) else ident)
    return ", ".join(dict.fromkeys(ids)) or "—"


def readable(name: str) -> str:
    name = re.sub(r"^test_", "", name)
    name = REQ.sub("", name)
    return re.sub(r"[_ ]+", " ", name).strip().capitalize()


def backend() -> Inventory:
    command = ["uv", "run", "pytest", "--collect-only", "-q", "--no-cov", "-p", "no:cacheprovider"]
    out = run(command, ROOT / "backend")
    files: OrderedDict[str, OrderedDict[str, int]] = OrderedDict()
    for line in out.splitlines():
        if "::" not in line:
            continue
        path, _, test = line.partition("::")
        base = test.split("[", 1)[0]
        files.setdefault(f"backend/{path}", OrderedDict())
        files[f"backend/{path}"][base] = files[f"backend/{path}"].get(base, 0) + 1
    return files


def vitest() -> Inventory:
    out = run(["pnpm", "exec", "vitest", "list"], ROOT / "frontend")
    files: OrderedDict[str, OrderedDict[str, int]] = OrderedDict()
    for line in out.splitlines():
        parts = [p.strip() for p in line.split(" > ")]
        if len(parts) < 2 or not parts[0].endswith((".ts", ".tsx")):
            continue
        name = " › ".join(parts[1:])
        name = re.sub(r" › [^›]*->[^›]*$", "", name)  # collapse it.each cases
        files.setdefault(f"frontend/{parts[0]}", OrderedDict())
        files[f"frontend/{parts[0]}"][name] = files[f"frontend/{parts[0]}"].get(name, 0) + 1
    return files


def playwright() -> Inventory:
    out = run(["pnpm", "exec", "playwright", "test", "--list"], ROOT / "frontend")
    files: OrderedDict[str, OrderedDict[str, int]] = OrderedDict()
    for line in out.splitlines():
        m = re.match(r"\s*\[(\w+)\] › ([\w.-]+):\d+:\d+ › (.+)$", line)
        if not m:
            continue
        browser, file, name = m.groups()
        key = f"frontend/e2e/{file}"
        files.setdefault(key, OrderedDict())
        label = f"{name} ({browser})"
        files[key][label] = files[key].get(label, 0) + 1
    return files


def table(title: str, files: Inventory, raw_names: bool) -> list[str]:
    total = sum(sum(t.values()) for t in files.values())
    lines = [f"### {title} — {total} test cases", ""]
    for path, tests in files.items():
        lines += [f"**`{path}`** ({sum(tests.values())})", ""]
        lines += ["| Test | Requirement | Cases |", "|---|---|---|"]
        for name, count in tests.items():
            shown = name if raw_names else readable(name)
            lines.append(f"| {shown.replace('|', '/')} | {requirement_ids(name)} | {count} |")
        lines.append("")
    return lines


def main() -> None:
    sections = [
        "_Generated by `python3 scripts/test_inventory.py`; do not edit by hand._",
        "",
        *table("Backend (pytest: unit, API, authorization matrix, migrations)", backend(), False),
        *table("Frontend (Vitest + Testing Library + MSW)", vitest(), True),
        *table("End-to-end (Playwright, composed stack)", playwright(), True),
    ]
    text = DOC.read_text(encoding="utf-8")
    head, _, rest = text.partition(START)
    _, _, tail = rest.partition(END)
    DOC.write_text(f"{head}{START}\n{chr(10).join(sections)}\n{END}{tail}", encoding="utf-8")
    print(f"Updated {DOC.relative_to(ROOT)}")  # noqa: T201 - command-line tool


if __name__ == "__main__":
    main()
