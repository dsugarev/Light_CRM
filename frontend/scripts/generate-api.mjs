// Generates src/api/schema.d.ts from the backend's OpenAPI document.
//
//   pnpm generate:api                      # from a running backend (localhost:8000)
//   pnpm generate:api path/to/openapi.json # from a file, e.g. exported by
//                                          # `uv run python -m app.cli export-openapi`
//
// The OpenAPI document is the only artifact shared with the backend.
import { writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

import openapiTS, { astToString } from 'openapi-typescript'

const DEFAULT_SOURCE = 'http://localhost:8000/api/v1/openapi.json'
const OUTPUT = resolve(import.meta.dirname, '../src/api/schema.d.ts')

const arg = process.argv[2] ?? process.env.OPENAPI_SOURCE ?? DEFAULT_SOURCE
const source = /^https?:\/\//.test(arg) ? new URL(arg) : new URL(`file://${resolve(arg)}`)

const ast = await openapiTS(source)
const header =
  '// Generated by `pnpm generate:api` from the backend OpenAPI document. Do not edit.\n\n'
await writeFile(OUTPUT, header + astToString(ast))
console.log(`Wrote ${OUTPUT} from ${source.href}`)
